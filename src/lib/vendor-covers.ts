function uniqueVendorVisual(category: string, vendorId: string, index = 0): string {
  const h = hash(`${category}:${vendorId}:${index}`);
  const palettes = [
    ["#7F1D1D", "#F59E0B", "#FEF3C7"],
    ["#14532D", "#D97706", "#ECFCCB"],
    ["#312E81", "#14B8A6", "#E0F2FE"],
    ["#831843", "#F97316", "#FCE7F3"],
    ["#164E63", "#EAB308", "#CCFBF1"],
    ["#3F2A1D", "#DC2626", "#FFEDD5"],
  ];
  const palette = palettes[h % palettes.length];
  const words = categoryVisualWords[category] ?? [category.replace(/_/g, " "), "vendor", "owanbe"];
  const word = words[(h >> 3) % words.length];
  const accent = words[(h >> 6) % words.length];
  const circles = Array.from({ length: 7 }, (_, i) => {
    const x = 12 + ((h >> (i + 1)) % 76);
    const y = 12 + ((h >> (i + 4)) % 64);
    const r = 10 + ((h >> (i + 7)) % 24);
    const opacity = 0.1 + (((h >> (i + 10)) % 18) / 100);
    return `<circle cx="${x}%" cy="${y}%" r="${r}%" fill="${i % 2 ? palette[1] : palette[2]}" opacity="${opacity.toFixed(2)}"/>`;
  }).join("");
  const lines = Array.from({ length: 6 }, (_, i) => {
    const y = 18 + i * 12 + ((h >> (i + 13)) % 5);
    const width = 28 + ((h >> (i + 17)) % 36);
    const x = i % 2 ? 54 - width / 3 : 12;
    return `<rect x="${x}%" y="${y}%" width="${width}%" height="1.4%" rx="4" fill="${palette[2]}" opacity="0.22"/>`;
  }).join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 900" role="img"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${palette[0]}"/><stop offset="0.58" stop-color="${palette[1]}"/><stop offset="1" stop-color="${palette[2]}"/></linearGradient><filter id="grain"><feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="3" stitchTiles="stitch"/><feColorMatrix type="saturate" values="0"/><feComponentTransfer><feFuncA type="table" tableValues="0 0.14"/></feComponentTransfer></filter></defs><rect width="1200" height="900" fill="url(#g)"/>${circles}${lines}<rect width="1200" height="900" filter="url(#grain)" opacity="0.45"/><path d="M70 720 C260 600 380 810 570 690 S900 550 1130 705 L1130 900 L70 900 Z" fill="${palette[0]}" opacity="0.28"/><text x="74" y="690" font-family="Georgia, 'Times New Roman', serif" font-size="96" font-weight="700" fill="white" opacity="0.94" letter-spacing="2">${word}</text><text x="78" y="760" font-family="Arial, sans-serif" font-size="34" font-weight="700" fill="white" opacity="0.72" letter-spacing="8">${accent.toUpperCase()}</text></svg>`;
  return `data:image/svg+xml;charset=UTF-8,${encodeURIComponent(svg)}`;
}

/**
 * Deterministic per-vendor visual signature applied on top of the cover image.
 *
 * Returns:
 *  - `filter`: CSS filter string (hue-rotate + small saturate/brightness shift)
 *  - `overlay`: CSS background string for a tinted gradient layer
 *  - `transform`: subtle scale + position shift so even identical base images
 *    crop to a slightly different framing
 *
 * All values are derived from the vendor id so they are stable across renders
 * and SSR/CSR. Eight discrete buckets per axis keep the look intentional
 * rather than random.
 */
export function tintFor(vendorId: string): {
  filter: string;
  overlay: string;
  transform: string;
} {
  if (!vendorId) {
    return { filter: "none", overlay: "transparent", transform: "none" };
  }
  const h = hash(vendorId);
  // Hue rotation in 8 buckets covering ±40deg (subtle but distinct)
  const hueBuckets = [-40, -28, -16, -6, 6, 16, 28, 40];
  const hue = hueBuckets[h % 8];
  // Saturation/brightness micro-shifts
  const sat = 0.92 + ((h >> 3) % 5) * 0.04; // 0.92 .. 1.08
  const bright = 0.94 + ((h >> 6) % 4) * 0.04; // 0.94 .. 1.06
  // Tint colour palette (Nigerian-warm: rust, gold, burgundy, plum, teal, indigo, emerald, amber)
  const tints = [
    "16 70% 45%",
    "43 75% 50%",
    "350 55% 35%",
    "280 40% 35%",
    "180 45% 35%",
    "230 45% 40%",
    "150 50% 32%",
    "30 80% 50%",
  ];
  const tint = tints[(h >> 9) % 8];
  // Gradient direction in 8 buckets
  const angle = ((h >> 12) % 8) * 45;
  // Subtle pan: ±4% on each axis from a 1.04 zoom
  const tx = (((h >> 15) % 9) - 4) * 0.5; // -2% .. +2%
  const ty = (((h >> 19) % 9) - 4) * 0.5;

  return {
    filter: `hue-rotate(${hue}deg) saturate(${sat.toFixed(2)}) brightness(${bright.toFixed(2)})`,
    overlay: `linear-gradient(${angle}deg, hsl(${tint} / 0.28) 0%, hsl(${tint} / 0.05) 60%, transparent 100%)`,
    transform: `scale(1.04) translate(${tx}%, ${ty}%)`,
  };
}


export function coverFor(
  category: string,
  cover_url: string | null | undefined,
  vendorId?: string,
): string {
  if (cover_url && cover_url.trim().length > 0) return cover_url;
  const pool = categoryCoverPool[category];
  if (pool && pool.length > 0) {
    const idx = vendorId ? hash(vendorId) % pool.length : 0;
    return pool[idx];
  }
  return vendorId ? uniqueVendorVisual(category, vendorId) : planner;
}

/**
 * Build a deterministic permutation of [0..n-1] seeded by `seed`.
 * Fisher–Yates with a tiny seeded LCG so different seeds give different orders.
 */
function seededPermutation(n: number, seed: number): number[] {
  const arr = Array.from({ length: n }, (_, i) => i);
  let s = (seed | 0) || 1;
  for (let i = n - 1; i > 0; i--) {
    s = (s * 1664525 + 1013904223) | 0;
    const j = Math.abs(s) % (i + 1);
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// Per-category permutation cache so all cards in a category share the same order.
const permCache = new Map<string, number[]>();
function getCategoryPermutation(category: string, n: number): number[] {
  const key = `${category}:${n}`;
  let perm = permCache.get(key);
  if (!perm) {
    perm = seededPermutation(n, hash(category));
    permCache.set(key, perm);
  }
  return perm;
}

/**
 * Position-aware cover picker that guarantees no variant repeats until the
 * full pool has been shown. Within a category list:
 *  - positions 0..n-1 walk a category-seeded permutation of all variants,
 *    so the first n cards are guaranteed to all be different
 *  - positions n..2n-1 walk the same permutation rotated by a vendor-derived
 *    offset, so block N never lines up with block N-1
 *
 * Vendors with a real `cover_url` (uploaded or AI-generated) keep theirs.
 */
export function coverForAt(
  category: string,
  cover_url: string | null | undefined,
  vendorId: string,
  index: number,
): string {
  if (cover_url && cover_url.trim().length > 0) return cover_url;
  const pool = categoryCoverPool[category];
  if (pool && pool.length > 0) {
    // Deterministic, category-aware permutation: every card in the first
    // `pool.length` positions gets a different on-category photo, and the
    // vendor id offsets later blocks so they don't line up.
    const perm = getCategoryPermutation(category, pool.length);
    const offset = hash(vendorId) % pool.length;
    return pool[perm[(index + offset) % pool.length]];
  }
  return uniqueVendorVisual(category, vendorId, index);
}

